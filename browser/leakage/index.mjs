function elementSVG(name, attributes, content) {
  const element = document.createElementNS(svgNS, name);
  Object.entries(attributes).forEach(([key, value]) => element.setAttribute(key, value));
  if (content !== undefined) element.textContent = content;
  return element;
}

function renderChart(svg, legend, result, detail) {
  const width = 450, height = 205, left = 42, top = 12, right = 12, bottom = 36;
  const xEnd = width - right;
  const yEnd = height - bottom;
  const duration = result.parameters.duration_ns;
  const maximum = detail ? Math.min(1, Math.max(.0001, result.peak_leakage * 1.08)) : 1;
  const xAt = time => (left + (xEnd - left) * time / duration).toFixed(2);
  const yAt = probability => (yEnd - (yEnd - top) * probability / maximum).toFixed(2);
  const lines = result.populations.flatMap((values, index) => index < 2 && detail ? [] : [{label: `|${index}⟩`, index, values}]);
  lines.push({label: 'Total leakage', index: 'total', values: result.leakage});
  const children = [elementSVG('title', {}, detail ? 'Leakage populations over time' : 'Transmon level populations over time')];
  for (let index = 0; index <= 4; index++) {
    const probability = index * maximum / 4;
    const y = yAt(probability);
    const label = detail ? Number((100 * probability).toPrecision(2)) : 100 * probability;
    children.push(elementSVG('line', {x1:left, x2:xEnd, y1:y, y2:y, class:'leakage-grid'}));
    children.push(elementSVG('text', {x:left - 5, y:Number(y) + 3, 'text-anchor':'end'}, `${label}%`));
    const time = index * duration / 4;
    const x = xAt(time);
    children.push(elementSVG('line', {x1:x, x2:x, y1:top, y2:yEnd, class:'leakage-grid'}));
    children.push(elementSVG('text', {x, y:yEnd + 17, 'text-anchor':'middle'}, Number(time.toFixed(2))));
  }
  children.push(elementSVG('text', {x:(left + xEnd)/2, y:height - 2, 'text-anchor':'middle'}, 'Time (ns)'));
  const keys = [];
  for (const {label, index, values} of lines) {
    const path = values.map((value, sample) => `${sample === 0 ? 'M' : 'L'}${xAt(result.time_ns[sample])},${yAt(value)}`).join(' ');
    children.push(elementSVG('path', {d:path, fill:'none', 'vector-effect':'non-scaling-stroke', class:`leakage-line leakage-color-${index}`}));
    const key = document.createElement('span');
    const swatch = document.createElement('i');
    swatch.classList.add('leakage-key', `leakage-color-${index}`);
    key.append(swatch, label);
    keys.push(key);
  }
  svg.replaceChildren(...children);
  legend.replaceChildren(...keys);
}

export function mountLeakage(root, {getEvents = () => []} = {}) {
  root.setAttribute('aria-labelledby', 'transmon-leakage-heading');
  root.innerHTML = panel;
  const $ = selector => root.querySelector(selector);
  const form = $('form');
  const input = field => $(`[data-field="${field}"]`);
  const drives = input('drive');
  const duration = input('duration');
  const run = $('.leakage-run');
  const cancel = $('.leakage-cancel');
  const status = $('.leakage-status');
  const plot = $('.leakage-result');
  const detail = $('.leakage-detail');
  let events = [];
  let selected;
  let lastResult;
  let lastSource;
  let running = false;
  let worker;
  let watchdog;
  let activeSource;
  let activeParameters;
  let priorSignature;
  let hasRun = false;

  function parameters() {
    return {
      levels: Number(input('levels').value),
      initial: Number(input('initial').value),
      duration_ns: duration.valueAsNumber,
      angle_rad: selected?.angle,
      phase_rad: selected?.phase,
      detuning_mhz: input('detuning').valueAsNumber,
      anharmonicity_mhz: input('anharmonicity').valueAsNumber,
      drag_beta_ns: input('drag').valueAsNumber,
    };
  }

  function state(message, kind = '') {
    status.textContent = message;
    status.dataset.kind = kind;
  }

  function selectionState() {
    const currentSignature = JSON.stringify([selected?.id, parameters()]);
    if (currentSignature !== priorSignature && !running) {
      const stale = lastResult && (lastSource?.id !== selected?.id || JSON.stringify(lastResult.parameters) !== JSON.stringify(parameters()));
      if (!selected) state('Add H, X, Y, Ry, or CX to choose a drive.');
      else if (stale) state('Showing the previous result. Run again to test the current settings.');
      else if (lastResult) state(`Computed in your browser with QuTiP ${lastResult.qutip_version}.`);
      else state(hasRun ? 'Ready to compute a pulse.' : 'First run downloads about 36 MB from QuTiP.');
    }
    priorSignature = currentSignature;
    run.disabled = running || !selected;
  }

  function selectEvent(id) {
    const event = events.find(item => String(item.id) === String(id));
    if (!event) return false;
    if (String(selected?.id) !== String(event.id) || selected?.duration !== event.duration) duration.value = String(event.duration);
    selected = event;
    drives.value = String(event.id);
    $('.leakage-drive-context').textContent = `${event.duration} ns in schedule · rotation ${deg(event.angle)} · commanded phase ${deg(event.phase)}`;
    selectionState();
    return true;
  }

  function update(compiledEvents = getEvents()) {
    const old = selected?.id;
    events = compiledEvents.filter(eligible);
    const choices = events.map(event => new Option(driveLabel(event), event.id));
    drives.replaceChildren(...(choices.length ? choices : [new Option('No drive in the circuit', '')]));
    drives.disabled = !choices.length;
    if (choices.length) {
      if (!selectEvent(old)) selectEvent(events[0].id);
    } else {
      selected = undefined;
      $('.leakage-drive-context').textContent = '';
      selectionState();
    }
  }

  function redraw() {
    if (lastResult) renderChart($('.leakage-chart'), $('.leakage-legend'), lastResult, detail.checked);
  }

  function renderResult(result, source) {
    lastResult = result;
    lastSource = source;
    $('.leakage-empty').hidden = true;
    plot.hidden = false;
    const metrics = $('.leakage-metrics');
    metrics.replaceChildren(...[
      ['Peak sampled leakage', result.peak_leakage], ['Final leakage', result.final_leakage],
      ['Final |1⟩ population', result.populations[1].at(-1)],
    ].map(([name, value]) => {
      const metric = document.createElement('div');
      const number = document.createElement('strong');
      number.textContent = percent(value);
      const label = document.createElement('span');
      label.textContent = name;
      metric.append(number, label);
      return metric;
    }));
    const resultParameters = result.parameters;
    const notices = [`${driveLabel(source)} · ${resultParameters.duration_ns} ns · ${resultParameters.levels} levels · initial |${resultParameters.initial}⟩.`];
    if (result.max_top_level_population > .01) notices.push('The highest retained level exceeds 1% population. Compare with another level.');
    if (result.norm_error > 1e-5) notices.push('The numerical normalization error exceeds 0.001%; interpret this example with care.');
    $('.leakage-context').textContent = notices.join(' ');
    redraw();
  }

  function finish() {
    clearTimeout(watchdog);
    running = false;
    cancel.hidden = true;
    run.disabled = !selected;
  }

  function reset(message, kind) {
    worker?.terminate();
    worker = undefined;
    finish();
    state(message, kind);
  }

  form.addEventListener('input', event => {
    if (event.target === drives) selectEvent(drives.value);
    else selectionState();
  });
  detail.addEventListener('change', redraw);
  cancel.addEventListener('click', () => reset('Simulation cancelled.'));
  form.addEventListener('submit', event => {
    event.preventDefault();
    if (!selected || running) return;
    hasRun = true;
    running = true;
    run.disabled = true;
    cancel.hidden = false;
    activeSource = selected;
    activeParameters = parameters();
    state('Starting the browser solver…');
    try {
      if (!worker) {
        const currentWorker = new Worker(new URL('./worker.js', import.meta.url));
        worker = currentWorker;
        currentWorker.onmessage = ({data}) => {
          if (worker !== currentWorker) return;
          if (data.type === 'progress') state(`${data.message}…`);
          if (data.type === 'result') {
            finish();
            renderResult(data.result, activeSource);
            priorSignature = undefined;
            selectionState();
          }
          if (data.type === 'error') {
            console.error(data.message);
            reset('The QuTiP solver could not finish. Check your connection and model settings, then try again.', 'error');
          }
        };
        currentWorker.onerror = () => {
          if (worker === currentWorker) reset('The QuTiP worker could not start. Reload this page and try again.', 'error');
        };
      }
      worker.postMessage({parameters: activeParameters});
      watchdog = setTimeout(() => reset('The runtime took longer than two minutes. Try again once your connection is available.', 'error'), 120000);
    } catch (error) {
      console.error(error);
      reset('This browser could not start the QuTiP worker.', 'error');
    }
  });

  update();
  return {update, selectEvent};
}
