const svgNS = 'http://www.w3.org/2000/svg';
const TAU = 2 * Math.PI;
const deg = angle => `${Number((360 * angle / TAU).toFixed(2))}°`;
const percent = value => value > 0 && value < .0001 ? `${(100 * value).toExponential(2)}%` : `${(100 * value).toFixed(2)}%`;
const eligible = event => event.kind === 'drive' && event.duration > 0;
const driveLabel = event => `Step ${event.column + 1} · q${event.qubit} · ${event.label}${event.gate === 'CX' ? ` (CX at ${event.start} ns)` : ''}`;
const numberField = (title, id, initial, min, max, step = 'any') => `<label>${title}<input data-field="${id}" type="number" value="${initial}" min="${min}" max="${max}" step="${step}" required></label>`;

